import { randomUUID, randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { cloudStagingConfig, CLOUD_STAGING_REF } from "./cloud-staging.mjs";

const config = cloudStagingConfig(process.env);
const options = { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } };
const admin = createClient(config.url, config.service, options);
const client = createClient(config.url, config.anon, options);
// Reserved domain; no user mailbox or production credential is used.
const email = `signup-${randomUUID()}@example.test`;
try {
  const response = await client.auth.signUp({ email, password: randomBytes(32).toString("hex") });
  const result = {
    at: new Date().toISOString(), projectRef: CLOUD_STAGING_REF,
    status: response.error ? "blocked" : "confirmation-delivery-not-verified",
    publicRegistrationAttempted: true, errorCode: response.error?.code || null,
    httpStatus: response.error?.status || null,
    emailDelivery: "not verified; no real mailbox or custom SMTP authorized",
    limitation: "Admin-created account login/RLS tests do not validate public registration or email confirmation delivery.",
  };
  writeFileSync(new URL("../docs/studyhub2/cloud-registration-results.json", import.meta.url), JSON.stringify(result, null, 2) + "\n");
  console.log(JSON.stringify(result, null, 2));
} finally {
  // Clean only the exact synthetic email generated by this invocation, including an unconfirmed user.
  const listed = await admin.auth.admin.listUsers({ page: 1, perPage: 100 });
  if (listed.error) throw Error("Cannot verify synthetic signup cleanup");
  for (const user of listed.data.users.filter((item) => item.email === email)) {
    if ((await admin.auth.admin.deleteUser(user.id)).error) throw Error("Cannot clean synthetic signup");
  }
}
